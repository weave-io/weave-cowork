import { launch, person, BASE, SHOTS, expect, ok } from './lib.mjs'
const browser = await launch()
const A = await person(browser), R = await person(browser)
const a = A.page, r = R.page
const shot = (p, name) => p.screenshot({ path: SHOTS + `phase1-${name}.png` })

// 1. set up
await a.goto(BASE)
await a.getByRole('heading', { name: 'Set up your server' }).waitFor()
await shot(a, 'setup')
await a.fill('[name=serverName]', 'Lumen Labs'); await a.fill('[name=username]', 'alex')
await a.fill('[name=displayName]', 'Alex'); await a.fill('[name=password]', 'correct horse')
await a.click('button[type=submit]')
await a.waitForSelector('[data-channel=general]')
expect(await a.textContent('[data-testid=channel-title]').then(t => t.includes('general')), 'Alex lands in #general after setup')
expect((await a.textContent('[data-testid=server-menu]')).includes('Lumen Labs'), 'server is named Lumen Labs')

// 2. sign out / in, wrong password
await a.click('[data-testid=user-menu]'); await a.click('[data-testid=sign-out]')
await a.getByRole('heading', { name: /Sign in to Lumen Labs/ }).waitFor()
await a.fill('[name=username]', 'alex'); await a.fill('[name=password]', 'nope nope nope')
await a.click('button[type=submit]')
await a.waitForSelector('[data-testid=auth-error]')
expect((await a.textContent('[data-testid=auth-error]')).includes('Wrong username or password'), 'wrong password says so')
await shot(a, 'signin-error')
await a.fill('[name=password]', 'correct horse'); await a.click('button[type=submit]')
await a.waitForSelector('[data-channel=general]')
ok('Alex signs back in')

// 3. channels
await a.click('[data-testid=create-channel]')
await a.fill('[name=name]', 'checkout-app'); await a.fill('[name=topic]', 'Cart, payment and order confirmation')
await a.click('button:has-text("Create channel")')
await a.waitForSelector('[data-testid=channel-title]:has-text("checkout-app")')
expect((await a.textContent('[data-testid=channel-topic]')).includes('Cart, payment'), 'created #checkout-app with a topic')
await a.click('[data-testid=create-channel]')
await a.fill('[name=name]', 'leads'); await a.click('[data-testid=private-switch]')
await a.click('button:has-text("Create channel")')
await a.waitForSelector('[data-channel=leads]')
expect(await a.locator('[data-channel=leads] [aria-label=Private]').count() === 1, 'created private #leads')

// 4. invite
await a.click('[data-testid=server-menu]'); await a.click('[data-testid=menu-invite-people]')
await a.click('[data-testid=create-invite]')
const link = await a.textContent('[data-testid=invite-link]')
expect(/\/invite\/[0-9a-f]{24}$/.test(link), 'invite link created: ' + link.replace(/https?:\/\/[^/]+/, ''))
await shot(a, 'invite-people')
// a second link we'll revoke
await a.click('[data-testid=create-invite]')
await a.waitForFunction((l) => document.querySelector('[data-testid=invite-link]').textContent !== l, link)
const link2 = await a.textContent('[data-testid=invite-link]')
await a.waitForFunction(() => document.querySelectorAll('[data-testid=invite-list] li').length === 2)
ok('two active links are listed')
await a.click(`[data-revoke="${link2.split('/').pop()}"]`)
await a.waitForFunction(() => document.querySelectorAll('[data-testid=invite-list] li').length === 1)
ok('revoked a link')
await a.keyboard.press('Escape')

const rPage2 = await R.ctx.newPage()
await rPage2.goto(link2.replace(/^https?:\/\/[^/]+/, BASE))
await rPage2.waitForSelector('[data-testid=invite-error]')
expect((await rPage2.textContent('[data-testid=invite-error]')).includes('revoked'), 'a revoked link says so')
await rPage2.close()

await r.goto(link.replace(/^https?:\/\/[^/]+/, BASE))
await r.getByRole('heading', { name: /Join Lumen Labs/ }).waitFor()
await shot(r, 'invite-signup')
await r.fill('[name=username]', 'rosa'); await r.fill('[name=displayName]', 'Rosa'); await r.fill('[name=password]', 'rosa-password')
await r.click('button[type=submit]')
await r.waitForSelector('[data-channel=general]')
expect((await r.textContent('[data-testid=me-name]')).includes('Rosa'), 'Rosa signs up via the link and lands in the app')
expect(await r.locator('[data-channel=checkout-app]').count() === 1, 'Rosa sees public #checkout-app')
expect(await r.locator('[data-channel=leads]').count() === 0, 'Rosa does not see private #leads')
expect(await r.locator('[data-testid=create-channel]').count() === 1, 'Rosa can create channels')
expect(await r.locator('[data-testid=channel-settings]').count() === 0, 'Rosa has no settings on #general')

// 5. run channels
await a.click('[data-channel=leads]')
await a.click('[data-testid=channel-settings]')
await a.click('[data-testid=add-member]'); await a.click('[role=option]:has-text("Rosa (@rosa)")')
await a.click('button:has-text("Add"):not(:has-text("Add to"))')
await r.waitForSelector('[data-channel=leads]')
ok('adding Rosa to #leads makes it appear for her, live')
await shot(a, 'channel-settings')
await a.click('[data-remove=rosa]')
await r.waitForSelector('[data-channel=leads]', { state: 'detached' })
ok('removing Rosa hides #leads again')
await a.keyboard.press('Escape')
// rename and re-topic #checkout-app
await a.click('[data-channel=checkout-app]')
await a.click('[data-testid=channel-settings]')
await a.fill('[name=topic]', 'Cart, payment, confirmation'); await a.click('button:has-text("Save")')
await a.waitForSelector('[role=status]')
await a.keyboard.press('Escape')
await r.click('[data-channel=checkout-app]')
await r.waitForFunction(() => document.querySelector('[data-testid=channel-topic]')?.textContent?.includes('confirmation,') === false)
// Rosa can't delete / manage a channel she didn't create; API check from her session
const status = await r.evaluate(async () => (await fetch('/api/channels/' + location.pathname.split('/')[2], { method: 'DELETE' })).status)
expect(status === 403, 'a member gets 403 deleting a channel they did not create')
// admin makes Rosa admin, then she can manage, then back
await a.click('[data-testid=server-menu]'); await a.click('[data-testid=menu-people]')
await a.click('[data-person=rosa] [data-testid=toggle-admin]')
await a.waitForSelector('[data-person=rosa]:has-text("Make member")')
await shot(a, 'people')
await r.waitForSelector('[data-testid=channel-settings]')
ok('Alex makes Rosa an admin; she gets channel settings live')
await a.click('[data-person=rosa] [data-testid=toggle-admin]')
await r.waitForSelector('[data-testid=channel-settings]', { state: 'detached' })
await a.keyboard.press('Escape')

// 6. posts and threads
await a.click('[data-channel=checkout-app]')
await r.click('[data-channel=checkout-app]')
await a.fill('[data-testid=composer]', 'Morning! The cart total is off by a cent.'); await a.keyboard.press('Enter')
await r.waitForSelector('text=The cart total is off by a cent.')
ok('Rosa sees Alex\'s post at once')
await r.fill('[data-testid=composer]', 'I can reproduce it with a 3-item cart.'); await r.keyboard.press('Enter')
await a.waitForSelector('text=I can reproduce it with a 3-item cart.')
ok('Alex sees Rosa\'s post at once')
await r.hover('[data-post]:has-text("cart total")')
await r.click('[data-post]:has-text("cart total") >> text=Reply in thread')
await r.waitForSelector('[data-testid=thread-panel]')
await r.fill('[data-testid=thread-panel] [data-testid=composer]', 'Rounding in the tax step, I think.'); await r.keyboard.press('Enter')
await a.waitForSelector('[data-post]:has-text("cart total") >> [data-testid=thread-card]:has-text("1 reply")')
ok('thread card shows "1 reply" live under the post')
await a.click('[data-testid=thread-card]')
await a.waitForSelector('[data-testid=thread-panel] >> text=Rounding in the tax step')
await a.fill('[data-testid=thread-panel] [data-testid=composer]', 'Agreed, checking that now.'); await a.keyboard.press('Enter')
await r.waitForSelector('[data-testid=thread-panel] >> text=Agreed, checking that now.')
await a.waitForSelector('[data-testid=thread-card]:has-text("2 replies")')
ok('replies stream both ways; card says "2 replies"')
await shot(a, 'thread')
await shot(r, 'feed-rosa')

// dark theme
const dctx = await browser.newContext({ viewport: { width: 1440, height: 860 }, colorScheme: 'dark' })
const dp = await dctx.newPage(); await dp.goto(BASE); await dp.fill('[name=username]', 'alex'); await dp.fill('[name=password]', 'correct horse'); await dp.click('button[type=submit]')
await dp.waitForSelector('[data-channel=checkout-app]'); await dp.click('[data-channel=checkout-app]'); await dp.waitForSelector('[data-testid=thread-card]')
await dp.screenshot({ path: SHOTS + 'phase1-dark.png' })

// last: delete a channel as admin
await a.click('[data-channel=leads]'); await a.click('[data-testid=channel-settings]')
await a.click('[data-testid=delete-channel]'); await a.click('[data-testid=confirm-action]')
await a.waitForSelector('[data-channel=leads]', { state: 'detached' })
ok('admin deletes #leads')
await browser.close()
console.log('PHASE 1 LIVE CHECK PASSED')
